<?php

namespace Brevo\Conversations\Requests;

use Brevo\Core\Json\JsonSerializableType;
use Brevo\Core\Json\JsonProperty;

class PostConversationsPushedMessagesRequest extends JsonSerializableType
{
    /**
     * @var ?string $agentId Agent ID. It can be found on the agent's page or received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a>.
     */
    #[JsonProperty('agentId')]
    public ?string $agentId;

    /**
     * @var ?string $groupId Group ID. It can be found on the group's page.
     */
    #[JsonProperty('groupId')]
    public ?string $groupId;

    /**
     * @var string $text Message text.
     */
    #[JsonProperty('text')]
    public string $text;

    /**
     * @var string $visitorId Visitor's ID received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a> or generated by you to <a href="https://developers.brevo.com/docs/customize-the-widget#identifying-existing-users">bind an existing user account to Conversations</a>.
     */
    #[JsonProperty('visitorId')]
    public string $visitorId;

    /**
     * @param array{
     *   text: string,
     *   visitorId: string,
     *   agentId?: ?string,
     *   groupId?: ?string,
     * } $values
     */
    public function __construct(
        array $values,
    ) {
        $this->agentId = $values['agentId'] ?? null;
        $this->groupId = $values['groupId'] ?? null;
        $this->text = $values['text'];
        $this->visitorId = $values['visitorId'];
    }
}

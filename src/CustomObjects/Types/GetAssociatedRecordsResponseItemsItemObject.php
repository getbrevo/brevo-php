<?php

namespace Brevo\CustomObjects\Types;

use Brevo\Core\Json\JsonSerializableType;
use Brevo\Core\Json\JsonProperty;
use Brevo\Core\Types\ArrayType;
use DateTime;
use Brevo\Core\Types\Date;

/**
 * The associated record. `ext_id`, `attributes`, `created_at` and `updated_at` are omitted when they are not available for the record.
 */
class GetAssociatedRecordsResponseItemsItemObject extends JsonSerializableType
{
    /**
     * Key-value pairs of attribute data for the associated record. Each key is the attribute **key** (e.g., `company_name`, `engine_type`), not the attribute label (e.g., "Company Name", "Engine Type").
     * For `category` or `multiple_category` attributes, the value is the option **key** (not the option label or option ID).
     * For contacts, attribute keys are returned in lowercase, for example `email`, `first_name`, `last_name`, `sms` and `ext_id`.
     *
     * @var ?array<string, mixed> $attributes
     */
    #[JsonProperty('attributes'), ArrayType(['string' => 'mixed'])]
    public ?array $attributes;

    /**
     * @var ?DateTime $createdAt Timestamp when the associated record was created. Not returned for contacts.
     */
    #[JsonProperty('created_at'), Date(Date::TYPE_DATETIME)]
    public ?DateTime $createdAt;

    /**
     * @var ?string $extId External ID of the associated record in your system. Not returned for contacts, whose external ID is available as `attributes.ext_id`.
     */
    #[JsonProperty('ext_id')]
    public ?string $extId;

    /**
     * @var ?int $id Internal ID of the associated record generated by Brevo.
     */
    #[JsonProperty('id')]
    public ?int $id;

    /**
     * @var ?DateTime $updatedAt Timestamp when the associated record was last updated. Not returned for contacts.
     */
    #[JsonProperty('updated_at'), Date(Date::TYPE_DATETIME)]
    public ?DateTime $updatedAt;

    /**
     * @param array{
     *   attributes?: ?array<string, mixed>,
     *   createdAt?: ?DateTime,
     *   extId?: ?string,
     *   id?: ?int,
     *   updatedAt?: ?DateTime,
     * } $values
     */
    public function __construct(
        array $values = [],
    ) {
        $this->attributes = $values['attributes'] ?? null;
        $this->createdAt = $values['createdAt'] ?? null;
        $this->extId = $values['extId'] ?? null;
        $this->id = $values['id'] ?? null;
        $this->updatedAt = $values['updatedAt'] ?? null;
    }

    /**
     * @return string
     */
    public function __toString(): string
    {
        return $this->toJson();
    }
}
